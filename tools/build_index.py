# Builds index.html: the persistent hand-drawn landscape, one host per scene, the voiceover
# and the sound effects. Scene slots come from assets/voice/vo_meta.json, so a voiceover
# regen only needs:  python3 tools/build_index.py
import json

meta = json.load(open("assets/voice/vo_meta.json"))
LEAD = 0.3          # silence before the first word
END_HOLD = 2.8      # hold on the last frame after the voice ends
secs = meta["sections"]
starts = [0.0] + [round(s["start_s"] + LEAD, 3) for s in secs[1:]]
total = round(secs[-1]["start_s"] + LEAD + secs[-1]["duration_s"] + END_HOLD - 0.5, 3)
ends = starts[1:] + [total]
names = ["welcome", "tutor", "start", "breakout", "joins", "goals", "stepout", "outro"]
# seams where the camera slides LEFT along the hill (scene 3 -> 4 is a zoom into the screen instead)
pan_seams = [starts[i] for i in (1, 2, 4, 5, 6, 7)]

# sound effects: (scene index, local time, file, volume)
SFX = [
    (0, 1.15, "chime", 0.22), (0, 1.85, "pop", 0.32), (0, 2.10, "pop", 0.28), (0, 2.36, "pop", 0.28),
    (0, 2.59, "pop", 0.28), (0, 6.20, "pop", 0.28),
    (1, 2.20, "pop", 0.3), (1, 6.35, "pop", 0.26), (1, 7.55, "pop", 0.26), (1, 9.10, "pop", 0.26),
    (1, 15.45, "sparkle", 0.22),
    (2, 2.95, "click-soft", 0.4), (2, 4.80, "pop", 0.26), (2, 5.40, "click", 0.35), (2, 8.25, "pop", 0.24),
    (2, 8.55, "pop", 0.24),
    (3, 1.80, "whoosh-short", 0.22), (3, 8.90, "pop", 0.3), (3, 10.95, "pop", 0.22), (3, 11.95, "pop", 0.2),
    (3, 12.90, "pop", 0.2), (3, 18.30, "pop", 0.22),
    (4, 0.65, "pop", 0.26), (4, 3.65, "ping", 0.18), (4, 5.00, "click", 0.35), (4, 8.65, "pop", 0.22),
    (5, 3.35, "pop", 0.24), (5, 5.35, "pop", 0.24), (5, 8.80, "pop", 0.26), (5, 10.00, "sparkle", 0.24),
    (6, 9.30, "click", 0.35), (6, 9.45, "pop", 0.26), (6, 15.75, "pop", 0.22), (6, 17.25, "pop", 0.22),
    (6, 11.45, "pop", 0.24), (6, 13.1, "pop", 0.24), (6, 19.05, "pop", 0.24),
    (7, 0.95, "pop", 0.22), (7, 1.95, "pop", 0.22), (7, 3.65, "pop", 0.22), (7, 4.95, "pop", 0.24),
    (7, 7.00, "chime", 0.25),
]
for s in pan_seams:
    SFX.append((None, s - 0.25, "whoosh-short", 0.12))
DUR = {"pop": 0.72, "chime": 1.6, "sparkle": 1.8, "click": 0.3, "click-soft": 0.3, "whoosh-short": 0.6, "ping": 0.9}

events = []
for sc, t, f, v in SFX:
    a = round((starts[sc] if sc is not None else 0) + t, 3)
    events.append((a, f, v))
events.sort()
lanes_end = []  # one lane per overlapping sound, lowest free lane first
audio_tags = []
for i, (a, f, v) in enumerate(events):
    d = DUR[f]
    lane = next((k for k, e in enumerate(lanes_end) if e <= a), None)
    if lane is None:
        lanes_end.append(0); lane = len(lanes_end) - 1
    lanes_end[lane] = a + d
    audio_tags.append(f'      <audio id="sfx-{i:02d}" class="clip" src="assets/sfx/{f}.mp3" data-start="{a}" '
                      f'data-duration="{d}" data-track-index="{3 + lane}" data-volume="{v}"></audio>')

hosts = []
for i, n in enumerate(names):
    d = round(ends[i] - starts[i], 3)
    hosts.append(f'''      <div id="{n}" data-composition-id="{n}" data-composition-src="compositions/{n}.html"
        data-start="{starts[i]}" data-duration="{d}" data-track-index="1" data-track-kind="graphics"
        data-width="1920" data-height="1080" style="z-index: 2"></div>''')

pan_js = "\n".join(
    f'      tl.to("#bg-hills", {{ x: {-(k + 1) * 320}, duration: 0.9, ease: "power2.inOut" }}, {round(s - 0.45, 3)});'
    for k, s in enumerate(pan_seams))

fonts = "\n".join(
    f'      @font-face {{ font-family: "DM Sans"; font-weight: {w}; src: url("assets/fonts/dm-sans-latin-{w}-normal.woff2") format("woff2"); }}'
    for w in (400, 500, 700, 800, 900))

html = f'''<!doctype html>
<!-- GENERATED by tools/build_index.py: edit that script, not this file. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="assets/vendor/gsap.min.js"></script>
    <style>
{fonts}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #f9f5ef; }}
      #root {{ width: 100%; height: 100%; position: relative; font-family: "DM Sans", sans-serif; background: #f9f5ef; }}
      #bg {{ position: absolute; inset: 0; z-index: 1; overflow: hidden; }}
      #bg-hills {{ position: absolute; left: 0; top: 0; width: 4200px; height: 1080px; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" data-width="1920" data-height="1080">
      <!-- the handbook landscape: one long hill the camera travels along -->
      <div id="bg" class="clip" data-start="0" data-duration="{total}" data-track-index="0" data-layout-ignore>
        <svg id="bg-hills" viewBox="0 0 4200 1080" fill="none" stroke-linecap="round">
          <path d="M0 830 C 420 790 760 720 1120 700 C 1460 680 1720 600 1980 590 C 2300 580 2560 690 2900 700 C 3260 712 3560 620 3860 610 C 4000 606 4120 620 4200 630 L4200 1080 L0 1080 Z" fill="#deefde" />
          <path d="M0 860 C 380 820 720 870 1060 920 C 1400 965 1700 940 1980 905 C 2300 866 2600 880 2900 915 C 3220 952 3520 930 3820 900 C 3980 885 4100 890 4200 896 L4200 1080 L0 1080 Z" fill="#5c9c62" />
          <g stroke="#a0cca3" stroke-width="4">
            <path d="M160 960 l-6 -22 M176 962 l4 -24" /><path d="M520 990 l-5 -20 M535 992 l3 -22" />
            <path d="M880 1010 l-6 -22 M896 1012 l4 -24" /><path d="M1250 1020 l-5 -20 M1265 1021 l3 -22" />
            <path d="M1610 1000 l-6 -22 M1626 1002 l4 -24" /><path d="M1960 985 l-5 -20 M1975 986 l3 -22" />
            <path d="M2330 975 l-6 -22 M2346 977 l4 -24" /><path d="M2700 1000 l-5 -20 M2715 1001 l3 -22" />
            <path d="M3080 1015 l-6 -22 M3096 1017 l4 -24" /><path d="M3450 1000 l-5 -20 M3465 1001 l3 -22" />
            <path d="M3820 985 l-6 -22 M3836 987 l4 -24" /><path d="M4120 990 l-5 -20 M4135 991 l3 -22" />
          </g>
        </svg>
      </div>

{chr(10).join(hosts)}

      <!-- Voiceover: HeyGen Cassidy (assets/voice/vo-full.mp3, built by tools/make_vo_heygen.py) -->
      <audio id="vo" class="clip" src="assets/voice/vo-full.mp3" data-start="{LEAD}" data-track-index="2" data-volume="1"></audio>

      <!-- Sound effects on on-screen actions (no music bed, per the brief) -->
{chr(10).join(audio_tags)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      const tl = gsap.timeline({{ paused: true }});
      // the landscape rises in, then slides left at each scene change
      tl.fromTo("#bg-hills", {{ y: 300 }}, {{ y: 0, duration: 1.0, ease: "power3.out" }}, 0);
{pan_js}
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
'''
open("index.html", "w").write(html)
print("scenes:", list(zip(names, starts, [round(e - s, 3) for s, e in zip(starts, ends)])))
print("total", total, "sfx", len(audio_tags), "lanes", len(lanes_end))
